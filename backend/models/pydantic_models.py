"""
Pydantic Models - Full Stack Alignment
======================================
Strict Pydantic models matching MongoDB $jsonSchema validators.

RULES:
- All fields use camelCase (SSOT)
- No system fields in Create models (generated by backend)
- Explicit type conversions (ObjectId, Date, int, bool)
- additionalProperties: false equivalent via model_config

Collections:
1. categories
2. category_requests
3. inquiries
4. inquiry_reports
5. product_requests
6. products
7. seller_listings
8. spec_templates
9. subscription_changes
10. subscriptions
11. users
"""

from pydantic import BaseModel, Field, field_validator, model_validator, ConfigDict
from typing import Optional, List, Dict, Any, Literal
from datetime import datetime
from enum import Enum
from bson import ObjectId


