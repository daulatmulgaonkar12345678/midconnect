# ================== 7. SELLER LISTINGS ==================

class ProductSnapshot(BaseModel):
    """Snapshot of product at listing creation time"""
    name: str
    categoryId: str  # Will be converted to ObjectId
    categoryName: str
    coverImageUrl: Optional[str] = None

class Availability(BaseModel):
    """Stock and availability info"""
    moq: int = Field(..., ge=1)
    stock: int = Field(default=0, ge=0)
    leadTimeDays: int = Field(default=1, ge=1)
    stockStatus: str = Field(default="in_stock")

class PricingSlab(BaseModel):
    """Price tier for quantity-based pricing"""
    quantityMin: int = Field(..., ge=1)
    quantityMax: Optional[int] = None  # null for "and above"
    pricePerUnit: float = Field(..., gt=0)
    currency: str = Field(default="INR")
    
    @model_validator(mode='after')
    def validate_quantity_range(self):
        if self.quantityMax is not None and self.quantityMin >= self.quantityMax:
            raise ValueError("quantityMin must be less than quantityMax")
        return self

class Pricing(BaseModel):
    """Pricing configuration"""
    pricingType: str = Field(default="slab")  # "slab" or "fixed"
    slabs: List[PricingSlab] = Field(..., min_length=1)

class ListingCreate(StrictModel):
    """
    Create listing (seller).
    System fields auto-generated: sellerId (from token), productSnapshot (lookup), createdAt, updatedAt
    """
    productId: str = Field(..., description="Product ObjectId as string")
    sellerType: str = Field(..., description="Manufacturer, Dealer, Distributor, Trader")
    specifications: Optional[Dict[str, Any]] = {}
    specTemplateIds: Optional[List[str]] = []
    specTemplateVersions: Optional[List[int]] = []
    availability: Availability
    pricing: Pricing
    images: List[str] = Field(..., min_length=1, description="Firebase URLs")
    status: ListingStatus = Field(default=ListingStatus.DRAFT)

class ListingUpdate(StrictModel):
    """Update listing (seller)"""
    sellerType: Optional[str] = None
    specifications: Optional[Dict[str, Any]] = None
    availability: Optional[Availability] = None
    pricing: Optional[Pricing] = None
    images: Optional[List[str]] = None
    status: Optional[ListingStatus] = None


