# ================== BASE CONFIGS ==================

class StrictModel(BaseModel):
    """Base model with strict validation - rejects extra fields"""
    model_config = ConfigDict(
        extra='forbid',  # Reject extra fields (like additionalProperties: false)
        str_strip_whitespace=True,
        validate_assignment=True
    )


# ================== 1. CATEGORIES ==================

class CategorySettings(BaseModel):
    """Category settings object"""
    allowedUnits: Optional[List[str]] = []
    defaultUnit: Optional[str] = None
    allowedSellerTypes: Optional[List[str]] = []
    dimensionsEnabled: Optional[bool] = False
    dimensionUnits: Optional[List[str]] = []
    dimensionFormat: Optional[str] = None
    dropdownOverrides: Optional[Dict[str, Any]] = None

class CategoryCreate(StrictModel):
    """
    Create category (admin only).
    System fields auto-generated: createdAt, updatedAt, createdBy
    """
    name: str = Field(..., min_length=1, max_length=200)
    description: Optional[str] = None
    imageUrl: Optional[str] = None  # Firebase URL
    icon: Optional[str] = None
    displayOrder: int = Field(default=0, ge=0)
    settings: Optional[CategorySettings] = None
    isActive: bool = True

class CategoryUpdate(StrictModel):
    """Update category (admin only)"""
    name: Optional[str] = Field(None, min_length=1, max_length=200)
    description: Optional[str] = None
    imageUrl: Optional[str] = None
    icon: Optional[str] = None
    displayOrder: Optional[int] = Field(None, ge=0)
    settings: Optional[CategorySettings] = None
    isActive: Optional[bool] = None


